import { patch } from "@web/core/utils/patch";
import { ProductTemplateAccounting } from "@point_of_sale/app/models/accounting/product_template_accounting";

console.log("[CUSTOM PRICELIST] JS MODULE LOADED");

patch(ProductTemplateAccounting.prototype, {
    getPrice(
        pricelist,
        quantity,
        priceExtra = 0,
        recurring = false,
        variant = false,
        originalLine = false,
        relatedLines = []
    ) {
        const product = variant;
        const productTmpl = variant?.product_tmpl_id || this;

        const standardPrice = variant
            ? variant.standard_price
            : this.standard_price;

        /*
         * Use the template list price here.
         *
         * We add priceExtra ourselves below because variant.lst_price
         * can already contain the variant's price_extra.
         *
         * This prevents the addon from being counted twice.
         */
        const basePrice = this.list_price;

        // Let normal Odoo calculate the price first.
        const price = super.getPrice(
            pricelist,
            quantity,
            priceExtra,
            recurring,
            variant,
            originalLine,
            relatedLines
        );

        if (!pricelist) {
            return price;
        }

        // ---------------------------------------------------------
        // PRODUCT-SPECIFIC RULES
        // ---------------------------------------------------------

        const productRules = (
            product?.backLink?.(
                "<-product.pricelist.item.product_id"
            ) || []
        )
            .filter(
                (rule) =>
                    rule.pricelist_id.id === pricelist.id
            )
            .sort(
                (a, b) =>
                    b.min_quantity - a.min_quantity
            );

        // ---------------------------------------------------------
        // PRODUCT TEMPLATE RULES
        // ---------------------------------------------------------

        const tmplRules = (
            productTmpl.backLink(
                "<-product.pricelist.item.product_tmpl_id"
            ) || []
        )
            .filter(
                (rule) =>
                    rule.pricelist_id.id === pricelist.id &&
                    !rule.product_id
            )
            .sort(
                (a, b) =>
                    b.min_quantity - a.min_quantity
            );

        // ---------------------------------------------------------
        // GLOBAL / CATEGORY RULES
        // ---------------------------------------------------------

        const generalRulesIds =
            pricelist.getGeneralRulesIdsByCategories(
                this.parentCategories
            );

        const rules =
            this.models["product.pricelist.item"]
                .readMany([
                    ...productRules.map(
                        (rule) => rule.id
                    ),
                    ...tmplRules.map(
                        (rule) => rule.id
                    ),
                    ...generalRulesIds,
                ])
                .filter(
                    (rule) =>
                        !rule.min_quantity ||
                        rule.min_quantity <= quantity
                );

        const rule = rules.length && rules[0];

        if (!rule) {
            return price;
        }

        // ---------------------------------------------------------
        // CUSTOM: COST + X% OF MARGIN
        // ---------------------------------------------------------

        if (rule.base === "cost_sales_average") {
            /*
             * priceExtra is the extra price generated by the
             * selected product configuration/variant.
             *
             * We treat the addon as pure cost/pass-through:
             *
             *     adjusted cost  = base cost + addon
             *     adjusted sales = base sales + addon
             *
             * Therefore the addon itself does not create margin.
             */

            const addonPrice = priceExtra || 0;

            const cost =
                standardPrice + addonPrice;

            const salesPrice =
                basePrice + addonPrice;

            const margin =
                salesPrice - cost;

            const marginPercentage =
                rule.margin_percentage ?? 50;
            console.log('margin percentage', rule, rule.margin_percentage, marginPercentage);
            const marginToKeep =
                margin *
                (marginPercentage / 100);

            const finalPrice =
                cost + marginToKeep;

            console.log(
                "[CUSTOM PRICELIST] CUSTOM RULE APPLIED",
                {
                    product:
                        productTmpl.display_name,

                    pricelist:
                        pricelist.name,

                    ruleId:
                        rule.id,

                    standardPrice,
                    basePrice,
                    addonPrice,

                    cost,
                    salesPrice,
                    margin,

                    marginPercentage,
                    marginToKeep,

                    finalPrice,
                }
            );

            return finalPrice;
        }

        // ---------------------------------------------------------
        // NORMAL ODOO RULE
        // ---------------------------------------------------------

        return price;
    },
});